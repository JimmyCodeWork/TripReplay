// Generates packages/map/src/places/variants.ts from the OpenCC character dictionaries.
//
// Usage: node tools/variants/src/main.ts <directory>
// where <directory> holds the files below, downloaded from
// https://raw.githubusercontent.com/BYVoid/OpenCC/<COMMIT>/data/dictionary/<file>.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { foldTable, parseDictionary, renderModule, simplifiedTable } from "./fold.ts";

const COMMIT = "9e9d730659fc7db366b43b4437b307444d87e23e";

/** Applied in this order: Simplified to Traditional first, so that Traditional forms become the folded forms. */
const FILES: readonly [name: string, sha256: string][] = [
  ["STCharacters.txt", "a0ca1601c70648cf48b33c3c6210ccbecc5c7eead4b4c3daf76587ba2c03582b"],
  ["JPShinjitaiCharacters.txt", "12cec7250b873ef52b36d8f92218d4f92c0aaf5d8cd7c58fe42d9785bdcdc43a"],
  ["TWVariants.txt", "245b94eb5842957e735dd44b7e7d4ff469a3643126cc8fa511adda5281e9cb86"],
  ["HKVariants.txt", "e5cd4345303224587102f2c9e4d2b67d2b7e349c6ce9152e4a118f4656cf7302"],
];

const OUTPUT = "packages/map/src/places/variants.ts";

const directory = process.argv[2];
if (!directory) {
  console.error("Usage: node tools/variants/src/main.ts <directory with the OpenCC dictionaries>");
  process.exit(1);
}

const dictionaries = FILES.map(([name, sha256]) => {
  const bytes = readFileSync(join(directory, name));
  const actual = createHash("sha256").update(bytes).digest("hex");
  if (actual !== sha256) {
    console.error(`${name}: SHA-256 ${actual} does not match the pinned ${sha256}`);
    process.exit(1);
  }
  return parseDictionary(bytes.toString("utf8"));
});

const table = foldTable(dictionaries);
const [simplified = [], , taiwan = []] = dictionaries;
const traditional = simplifiedTable(simplified, taiwan);
const header = [
  "// Generated by tools/variants from the OpenCC dictionaries at commit",
  `// ${COMMIT}: ${FILES.map(([name]) => name).join(", ")}.`,
  "// OpenCC: Copyright BYVoid and contributors, Apache License 2.0 (see OPENCC-LICENSE.txt).",
  "// Do not edit; regenerate instead.",
].join("\n");
writeFileSync(OUTPUT, renderModule({ VARIANT_PAIRS: table, SIMPLIFIED_PAIRS: traditional }, header));
console.log(`${OUTPUT}: ${table.size} variant characters, ${traditional.size} Simplified characters`);
